  function init(cb) {
    onChange = cb;
    lang = detect();
    applyDom();
    fillLangSelect();
    try {
      I18n._ensureVoices?.();
    } catch (_) {}
  }

  function fillLangSelect() {
    const sel = document.getElementById("langSelect");
    if (!sel) return;
    const current = sel.value || lang;
    sel.innerHTML = SUPPORTED.map(
      (c) => `<option value="${c}">${LANG_NAMES[c]}</option>`
    ).join("");
    sel.value = SUPPORTED.includes(current) ? current : lang;
    if (!sel.dataset.langBound) {
      sel.dataset.langBound = "1";
      sel.addEventListener("change", () => setLang(sel.value));
    }
  }

  function setLang(code) {
    if (!SUPPORTED.includes(code)) return;
    lang = code;
    try {
      if (typeof CarBrowser !== "undefined" && CarBrowser.setPref) {
        CarBrowser.setPref("lang", code);
      } else {
        localStorage.setItem(STORAGE_LANG, code);
      }
    } catch (_) {}
    applyDom();
    fillLangSelect();
    if (onChange) onChange(code);
    try {
      document.dispatchEvent(new CustomEvent("etubu:lang-change", { detail: { lang: code } }));
    } catch (_) {}
    try {
      CarBrowser?.refreshTeslaHint?.();
    } catch (_) {}
  }

